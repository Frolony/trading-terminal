//! W6.2 (first pass) — the labeled-route validation harness.
//!
//! The S13 contract: every label ships with confidence AND evidence, and
//! anything below 0.70 is a guess, never a verdict. This file is the
//! machine's report card against *labeled ground truth*: each case states
//! what the fixture IS — written from the shape of the flow, independently
//! of what the classifier says — and the harness checks the machine
//! against it. Run with `cargo test -- --nocapture` to see the full
//! report; the test itself accumulates every case's outcome and fails once,
//! at the end, so a red run still prints the complete report.
//!
//! ## What this pass covers — and what it does not
//!
//! * Covered: the workflow classifiers (all ten [`Label`]s that have a
//!   candidate arm, plus the guards) and the attestation-timing detectors,
//!   against a synthetic labeled corpus shaped by the S11 dictionary.
//! * NOT covered yet: ground truth from our own devnet swarm traffic
//!   (generated by us, so the labels are known exactly) and from real
//!   labeled mainnet routes. Those are the second half of W6.2 and stay
//!   open — this corpus is synthetic, and the report says so.
//! * Two honest gaps this pass *pins* rather than fixes, as
//!   [`WfExpect::KnownLimitation`]: (1) a fully-closed market-maker
//!   inventory unwind reads as [`Label::WashLoop`] — the stitcher's
//!   mint-based circularity rule cannot distinguish it from manufactured
//!   movement (a false-accusation risk); (2) [`Label::PositionClose`] has
//!   no constructible fixture under the current stitcher — hop 1 always
//!   debits the origin wallet, and any same-mint return home closes the
//!   loop first (wash, priority 1), so a close intent either mislabels as
//!   WashLoop (return home) or as PositionOpen (return swept elsewhere).
//!   The cases assert the machine's CURRENT reading so that any future fix
//!   flips them loudly; the report names both as launch-gate blockers.
//!
//! The W6.2 gate stays CLOSED after this pass: no label is user-facing
//! until (a) the devnet-swarm ground-truth pass lands, (b) the MM-unwind /
//! WashLoop overlap is resolved at the stitcher, and (c) the PositionClose
//! reachability question is ruled on (windowed-ingestion shape, or the arm
//! is retired).

use tracer_s13::attestation::{
    attest, AttestationLabel, AttestationRecord, CausalTime, RealizedEvent,
};
