#[allow(clippy::too_many_arguments)] // test-only event builder; arity is the point
fn ev(
    sig: &str,
    slot: u64,
    index: u32,
    from: &str,
    to: &str,
    mint: &str,
    amount: i128,
    program: &str,
    instruction: &str,
    fee: u64,
) -> TransferEvent {
    TransferEvent {
        signature: sig.to_string(),
        slot,
        index,
        timestamp_ms: 1_790_000_000_000 + slot * 400,
        from: from.to_string(),
        to: to.to_string(),
        mint: mint.to_string(),
        amount,
        program_id: program.to_string(),
        instruction: instruction.to_string(),
        fee_lamports: fee,
    }
}

fn realized(id: &str, hash: &str, slot: u64, index: u32) -> RealizedEvent {
    RealizedEvent {
        id: id.to_string(),
        hash: hash.to_string(),
        realized_at: CausalTime::at(slot, index),
        signature: format!("event-sig-{id}"),
    }
}

fn attestation(
    attester: &str,
    event_id: &str,
    certified_hash: &str,
    certified_at: (u64, u32),
    signed_at: (u64, u32),
) -> AttestationRecord {
    AttestationRecord {
        attester: attester.to_string(),
        event_id: event_id.to_string(),
        certified_hash: certified_hash.to_string(),
        certified_at: CausalTime::at(certified_at.0, certified_at.1),
        signed_at: CausalTime::at(signed_at.0, signed_at.1),
        signature: format!("att-sig-{attester}-{event_id}"),
    }
}

/// What the harness demands of one workflow fixture.
enum WfExpect {
    /// The fixture IS this shape; the machine must label it at ≥ min confidence.
    MustLabel { label: Label, min_confidence: f64 },
    /// The machine must not label this at all — a guess, with no label.
    MustStayUnclassified,
    /// A documented gap: asserts the machine's CURRENT reading (pins it so
    /// a future fix flips the case loudly) and carries the launch-gate note.
    KnownLimitation { observed_label: Label, min_confidence: f64, gate_note: &'static str },
}

struct WfCase {
    name: &'static str,
    /// What the fixture IS — stated from the flow's shape, independently of
    /// the classifier. This is the "labeled" in labeled-route validation.
    ground_truth: &'static str,
    events: Vec<TransferEvent>,
    expect: WfExpect,
}

struct AttCase {
    name: &'static str,
    ground_truth: &'static str,
    event: Option<RealizedEvent>,
    record: AttestationRecord,
    expect_label: Option<AttestationLabel>,
    min_confidence: f64,
}

