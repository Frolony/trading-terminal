/// The W6.2 validation run: every case checked, the full report printed,
/// failures accumulated so one red case never hides the rest.
#[test]
fn w62_labeled_route_validation_corpus() {
    let dict = default_dictionary();
    let wf_corpus = workflow_corpus();
    let att_corpus = attestation_corpus();
    let mut failures: Vec<String> = Vec::new();
    let mut passed = 0usize;
    let mut gate_blockers: Vec<(&str, &str)> = Vec::new();

    // Corpus calibration: every min_confidence floor must be reachable under
    // the sealed threshold — the seal demotes anything below it, so a floor
    // below the threshold could never pass. If CONFIDENCE_THRESHOLD moves,
    // this fails first and every floor must be re-derived.
    for case in &wf_corpus {
        let floor = match &case.expect {
            WfExpect::MustLabel { min_confidence, .. }
            | WfExpect::KnownLimitation { min_confidence, .. } => Some(*min_confidence),
            WfExpect::MustStayUnclassified => None,
        };
        if let Some(floor) = floor {
            assert!(
                floor >= CONFIDENCE_THRESHOLD,
                "case {}: min_confidence {floor:.2} below the {CONFIDENCE_THRESHOLD:.2} seal \
                 threshold — re-derive the corpus floors",
                case.name
            );
        }
    }
    for case in &att_corpus {
        assert!(
            case.expect_label.is_none() || case.min_confidence >= CONFIDENCE_THRESHOLD,
            "case {}: min_confidence below the seal threshold — re-derive the corpus floors",
            case.name
        );
    }

    println!("=== W6.2 labeled-route validation report (first pass: synthetic corpus) ===");
    println!("--- workflow classifiers ---");
    for case in &wf_corpus {
        let line = check_workflow_case(&dict, case);
        match line {
            Ok(note) => {
                passed += 1;
                println!("  [PASS] {}: {}", case.name, note);
            }
            Err(failure) => {
                failures.push(format!("{}: {}", case.name, failure));
                println!("  [FAIL] {}: {}", case.name, failure);
            }
        }
        if let WfExpect::KnownLimitation { gate_note, .. } = &case.expect {
            gate_blockers.push((case.name, *gate_note));
        }
    }

    println!("--- attestation-timing detectors ---");
    for case in &att_corpus {
        let line = check_attestation_case(case);
        match line {
            Ok(note) => {
                passed += 1;
                println!("  [PASS] {}: {}", case.name, note);
            }
            Err(failure) => {
                failures.push(format!("{}: {}", case.name, failure));
                println!("  [FAIL] {}: {}", case.name, failure);
            }
        }
    }

    let total = wf_corpus.len() + att_corpus.len();
    println!("--- summary: {passed}/{total} cases passed ---");
    println!("--- known limitations (launch-gate blockers, pinned above) ---");
    for (name, note) in &gate_blockers {
        println!("  [BLOCKER] {name}: {note}");
    }
    println!("--- gate: CLOSED. Synthetic corpus only; devnet-swarm ground truth pending. ---");
    println!("=== end of W6.2 validation report ===");

    assert!(
        failures.is_empty(),
        "labeled-route validation failures ({} of {}):\n  - {}",
        failures.len(),
        total,
        failures.join("\n  - ")
    );
}

fn check_workflow_case(
    dict: &tracer_s13::dictionary::Dictionary,
    case: &WfCase,
) -> Result<String, String> {
    let ingested =
        ingest(case.events.clone()).map_err(|e| format!("ingest rejected the fixture: {e:?}"))?;
    let wfs = reconstruct(&ingested);
    if wfs.len() != 1 {
        return Err(format!(
            "fixture stitched into {} workflows, expected exactly 1 (ground truth: {})",
            wfs.len(),
            case.ground_truth
        ));
    }
    let v = classify(dict, &wfs[0]);
    match case.expect {
        WfExpect::MustLabel { label, min_confidence } => {
            if v.is_guess() {
                return Err(format!(
                    "expected {:?} (ground truth: {}), machine stayed a guess: {:?}",
                    label, case.ground_truth, v.classification
                ));
            }
            let got = v.label().expect("not a guess, so a label exists");
            if got != label {
                return Err(format!(
                    "expected {:?}, machine labeled {:?} (ground truth: {})",
                    label, got, case.ground_truth
                ));
            }
            let conf = v.confidence();
            if conf < min_confidence {
                return Err(format!(
                    "labeled {:?} but confidence {conf:.2} < {min_confidence:.2}",
                    label
                ));
            }
            if v.evidence.is_empty() {
                return Err("labeled with no evidence attached".to_string());
            }
            Ok(format!("labeled {got:?} at {conf:.2} (ground truth: {})", case.ground_truth))
        }
        WfExpect::MustStayUnclassified => {
            if !v.is_guess() || v.label().is_some() {
                return Err(format!(
                    "must stay a guess (ground truth: {}), machine labeled {:?}",
                    case.ground_truth,
                    v.label()
                ));
            }
            Ok(format!("stayed a guess (ground truth: {})", case.ground_truth))
        }
        WfExpect::KnownLimitation { observed_label, min_confidence, .. } => {
            let got = v.label();
            if got != Some(observed_label) {
                return Err(format!(
                    "KNOWN LIMITATION CHANGED: pinned reading was {observed_label:?}, machine now says {got:?} — \
                     update this case (the gap may be fixed); ground truth: {}",
                    case.ground_truth
                ));
            }
            let conf = v.confidence();
            if conf < min_confidence {
                return Err(format!(
                    "pinned reading {observed_label:?} dropped to {conf:.2} < {min_confidence:.2}"
                ));
            }
            Ok(format!(
                "pinned current reading {observed_label:?} at {conf:.2} — launch-gate blocker, see report"
            ))
        }
    }
}

fn check_attestation_case(case: &AttCase) -> Result<String, String> {
    let v = attest(case.event.as_ref(), &case.record);
    match case.expect_label {
        Some(label) => {
            let got = v.label();
            if got != Some(label) {
                return Err(format!(
                    "expected {label:?}, machine said {got:?} (ground truth: {})",
                    case.ground_truth
                ));
            }
            let conf = v.confidence();
            if conf < case.min_confidence {
                return Err(format!(
                    "labeled {label:?} but confidence {conf:.2} < {:.2}",
                    case.min_confidence
                ));
            }
            Ok(format!("labeled {label:?} at {conf:.2} (ground truth: {})", case.ground_truth))
        }
        None => {
            if !v.is_guess() || v.label().is_some() {
                return Err(format!(
                    "unknown event must stay unclassified, machine labeled {:?}",
                    v.label()
                ));
            }
            Ok(format!("unclassified, not fraud (ground truth: {})", case.ground_truth))
        }
    }
}
